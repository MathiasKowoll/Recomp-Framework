#!/usr/bin/env python3
"""Generate runtime/gl_thunks.h: one guest-callable shim per OpenGL function in the macOS SDK's OpenGL/gl3.h
(the 4.1 core profile that macOS provides).

Guest (Win64) code calls GL through opengl32.dll imports and wglGetProcAddress pointers. GL types have the same
sizes on both sides and pointers are guest = host, so every argument passes through unchanged:
  - integer / pointer / enum args come from rcx, rdx, r8, r9, then the stack
  - GLfloat / GLclampf args come from xmm0-3 (same position), then the stack; GLdouble / GLclampd likewise
Functions that need translation (the emulated default framebuffer, extension strings, core-profile fixups) are
listed in MANUAL and written by hand in runtime/opengl.m. The generated gl_procs[] table lists every function,
generated or hand-written, for wglGetProcAddress.

usage: gen_gl.py gl3.h out.h
"""
import re, sys

MANUAL = {
    "glGetString", "glGetStringi", "glGetIntegerv", "glGetInteger64v", "glGetBooleanv", "glGetFloatv", "glGetDoublev",
    "glBindFramebuffer", "glDrawBuffer", "glDrawBuffers", "glReadBuffer", "glGetFramebufferAttachmentParameteriv",
    "glBindVertexArray", "glDeleteVertexArrays", "glPolygonMode", "glLineWidth", "glEnable", "glDisable", "glIsEnabled",
    "glShaderSource", "glCompileShader", "glLinkProgram", "glGetError", "glFlush", "glFinish",
    "glTexImage1D", "glTexImage2D", "glTexImage3D", "glTexSubImage1D", "glTexSubImage2D", "glTexSubImage3D",
    "glReadPixels", "glGetTexImage",
    "glGenQueries", "glDeleteQueries", "glBeginQuery", "glEndQuery", "glGetQueryObjectuiv", "glGetQueryObjectiv",
    "glGetQueryObjectui64v", "glGetQueryObjecti64v", "glQueryCounter", "glIsQuery", "glBeginQueryIndexed",
    "glBeginConditionalRender", "glEndConditionalRender",
}
FLOAT = {"GLfloat", "GLclampf"}
DOUBLE = {"GLdouble", "GLclampd"}
RET32 = {"GLenum", "GLuint", "GLint", "GLboolean", "GLbitfield", "GLsizei"}
RETPTR = {"const GLubyte *", "GLvoid*", "GLvoid *", "void *", "void*", "GLsync"}


def main(hdr, out):
    src = open(hdr).read()
    protos = re.findall(r"^GLAPI[ \t]+([^\n]+?)\s*APIENTRY\s+(gl\w+)\s*\(([^)]*)\)", src, re.M)
    seen, lines, names = set(), [], []
    for ret, name, params in protos:
        if name in seen: continue
        seen.add(name); names.append(name)
        if name in MANUAL: continue
        ret = " ".join(ret.split())
        ps = [] if params.strip() in ("void", "") else [" ".join(p.split()) for p in params.split(",")]
        args = []
        for i, p in enumerate(ps):
            m = re.match(r"(.*?)\s*\b(\w+)\s*(\[\w*\])?$", p)
            ty = m.group(1).strip() if m and m.group(1).strip() else p
            if m and m.group(3): ty += "*"
            base = ty.replace("const", "").strip()
            slot = ["A0", "A1", "A2", "A3"][i] if i < 4 else "AN(%d)" % i
            if base in FLOAT and "*" not in ty:
                args.append("AF(%d)" % i if i < 4 else "rdf(c->rsp + 8 + 8 * %d)" % i)
            elif base in DOUBLE and "*" not in ty:
                args.append("AD(%d)" % i if i < 4 else "rdd(c->rsp + 8 + 8 * %d)" % i)
            elif "*" in ty:
                args.append("(%s)(uintptr_t)%s" % (ty, slot))
            elif base.startswith("GL"):
                args.append("(%s)%s" % (ty, slot))
            else:
                raise SystemExit("%s: unhandled parameter type %r" % (name, ty))
        call = "%s(%s)" % (name, ", ".join(args))
        if ret in ("void", "GLvoid"): body = call + ";"
        elif ret in RET32: body = "RET((uint32_t)%s);" % call
        elif ret in RETPTR: body = "RET((uintptr_t)%s);" % call
        else: raise SystemExit("%s: unhandled return type %r" % (name, ret))
        lines.append('void I_opengl32_dll_%s(CPU *c) { GL_PRE(%s); %s GL_POST(%s); }' % (name, name, body, name))
    with open(out, "w") as f:
        f.write("// Generated by tools/gen_gl.py from the macOS SDK's OpenGL/gl3.h - do not edit.\n")
        f.write("// %d thunks; included by runtime/opengl.m, which defines GL_PRE / GL_POST and the MANUAL functions.\n\n" % len(lines))
        f.write("\n".join(lines))
        f.write("\n\n" + "".join("void I_opengl32_dll_%s(CPU *c);\n" % n for n in sorted(MANUAL & seen)))
        f.write("\nstatic const struct { const char *name; gfn fn; } gl_procs[] = {\n")
        f.write("".join('    { "%s", I_opengl32_dll_%s },\n' % (n, n) for n in sorted(names)))
        f.write("};\n")
    missing = MANUAL - seen
    if missing: raise SystemExit("MANUAL functions not in the header: %s" % sorted(missing))
    print("%s: %d thunks, %d hand-written" % (out, len(lines), len(MANUAL)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
