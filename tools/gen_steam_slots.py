#!/usr/bin/env python3
"""Generate runtime/steam_slots.h: one native stub per (Steam interface, vtable slot), each calling dispatch().

usage: gen_steam_slots.py NIF NSLOTS out.h   (NIF / NSLOTS as in runtime/steam.c)
"""
import sys

nif, nslots, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
with open(out, "w") as f:
    f.write("// generated by tools/gen_steam_slots.py: one native stub per (interface, vtable slot)\n")
    for i in range(nif):
        for s in range(nslots):
            f.write("static void st_%d_%d(CPU *c) { dispatch(c, %d, %d); }\n" % (i, s, i, s))
    f.write("static gfn slot_fns[NIF][NSLOTS] = {\n")
    for i in range(nif):
        f.write("  { %s },\n" % ", ".join("st_%d_%d" % (i, s) for s in range(nslots)))
    f.write("};\n")
